"""Write the public coverage page (docs/COVERAGE.md) from the shared database: counts only.

    python scripts/coverage.py [--out docs/COVERAGE.md]

Needs SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY in the environment (run it on your own machine, or in a
scheduled job that holds them as secrets). The same numbers are served, cached for an hour, at GET /api/v1/coverage.
"""

import argparse
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from api.v1._lib import coverage  # noqa: E402
from monitor_calibration.profiles import SCREEN_TECH_LABELS  # noqa: E402

DEFAULT_OUT = Path(__file__).resolve().parents[1] / "docs" / "COVERAGE.md"


def render(counts, when=None):
    """Markdown for the counts. Nothing but totals goes in."""
    when = when or time.strftime("%Y-%m-%d")
    pc = counts["phone_corrections"]
    lines = [
        "# Coverage",
        "",
        f"What the shared database knows, as of {when}. Counts only: no names, no per-person data. Generated by "
        "`scripts/coverage.py`.",
        "",
        "| | |",
        "| --- | --- |",
        f"| Phone models with a verified entry | {counts['phones_verified']} |",
        f"| Monitor models with a verified entry | {counts['monitors_verified']} |",
        f"| Phone models with a shared correction | {pc['phones_covered']} |",
        f"| Monitor models and picture modes with suggested settings | {counts['suggested_settings']['monitor_modes']} |",
        f"| Monitor models and picture modes with a measured reference profile | {counts['reference_profiles']['monitor_modes']} |",
        "",
        "Shared phone corrections by kind of screen:",
        "",
    ]
    by_tech = pc["by_screen_tech"]
    if by_tech:
        lines += ["| Screen | Corrections |", "| --- | --- |"]
        lines += [f"| {SCREEN_TECH_LABELS.get(t, t)} | {n} |" for t, n in by_tech.items()]
    else:
        lines.append("None yet.")
    lines += [
        "",
        "A correction, a suggestion or a profile only appears here once enough independent people agree "
        "(see [`DATA.md`](DATA.md)). You can help by sharing a session that used a reference monitor.",
        "",
    ]
    return "\n".join(lines)


def main(argv=None, store=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=str(DEFAULT_OUT))
    args = ap.parse_args(argv)
    from review import make_context

    ctx = make_context(store)
    Path(args.out).write_text(render(coverage.build(ctx.store)), encoding="utf-8")
    print("wrote", args.out)
    return 0


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    sys.exit(main())
